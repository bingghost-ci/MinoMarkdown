#!/usr/bin/env node
// Generates the two files that register the bundled fonts (T98):
//
//   src/features/reading/bundledFonts.css   the @font-face rules the app loads at startup
//   src/features/reading/fontTable.ts       the same faces as data, for exports to pick the subsets a document needs
//
//   node scripts/generate-font-table.mjs          # write both
//   node scripts/generate-font-table.mjs --check  # exit 1 if a committed file differs from a fresh one
//
// The app used to import each font package's style sheet as text, take it apart with regular expressions on
// every launch and write some 380 KB of @font-face rules into the page from JavaScript. That put half a
// megabyte of text into the entry bundle. Now the rules are an ordinary style sheet that the build resolves
// and the browser parses, and the table is loaded only when a document is exported.
//
// Run this after changing a font package's version or the list below; tests/reading-fonts.test.ts runs the
// check. The family names here are the ones in src/features/reading/fonts.ts, which the same test compares.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const outputs = { css: join(root, 'src/features/reading/bundledFonts.css'), table: join(root, 'src/features/reading/fontTable.ts') }

// Noto Serif SC and Noto Sans SC ship as about a hundred unicode-range subsets per weight, and WebKit fetches
// only the subsets a page uses. Western fonts are variable (one file holds every weight) and limited to the
// Latin subsets. A family without italics has no italic sheet.
const notoSubsets = /-(?:\d+|latin|latin-ext|cyrillic|vietnamese)-(?:400|700)-normal\.woff2$/
const latinSubsets = /-(?:latin|latin-ext)-wght-(?:normal|italic)\.woff2$/
const noto = (family, name) => ({ family, directory: `node_modules/@fontsource/${name}`, sheets: ['400.css', '700.css'], keep: notoSubsets })
const variable = (family, name) => ({ family, directory: `node_modules/@fontsource-variable/${name}`, sheets: ['wght-italic.css', 'wght.css'], keep: latinSubsets })
/** A font shipped as one file per weight: no subsets, so any text needs the whole file. A weight range lets 400 text use the 500 file. */
const whole = (family, files) => ({ family, files })

const families = [
  noto('Mino Noto Serif SC', 'noto-serif-sc'),
  noto('Mino Noto Sans SC', 'noto-sans-sc'),
  whole('Mino LXGW WenKai', [['node_modules/@fontsource/lxgw-wenkai/files/lxgw-wenkai-latin-500-normal.woff2', '100 599'], ['node_modules/@fontsource/lxgw-wenkai/files/lxgw-wenkai-latin-700-normal.woff2', '600 900']]),
  // Zhuque Fangsong and ChillHuoSong ship one regular weight; bold is synthesized (`font-synthesis: weight`).
  whole('Mino Zhuque Fangsong', [['src/assets/fonts/zhuque-fangsong/zhuque-fangsong-400.woff2', '100 900']]),
  whole('Mino Chill HuoSong', [['src/assets/fonts/chill-huosong/chill-huosong-400.woff2', '100 900']]),
  variable('Mino Source Serif 4', 'source-serif-4'),
  variable('Mino Literata', 'literata'),
  variable('Mino EB Garamond', 'eb-garamond'),
  variable('Mino Inter', 'inter'),
  variable('Mino JetBrains Mono', 'jetbrains-mono'),
  variable('Mino Fira Code', 'fira-code'),
  variable('Mino Source Code Pro', 'source-code-pro'),
]

/** Every face, in the order it is registered: family, path from the project root, weight, style, unicode-range. */
export function faces() {
  return families.flatMap((entry) => {
    if (entry.files) return entry.files.map(([path, weight]) => ({ family: entry.family, path, weight, style: 'normal', unicodeRange: null }))
    return entry.sheets.map((sheet) => join(root, entry.directory, sheet)).filter((sheet) => existsSync(sheet)).flatMap((sheet) => readFileSync(sheet, 'utf8').split('@font-face').slice(1).flatMap((block) => {
      const file = /files\/([^)]+\.woff2)/.exec(block)?.[1]
      const weight = /font-weight:\s*(\d+(?:\s+\d+)?)/.exec(block)?.[1]
      const unicodeRange = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim() ?? null
      return file && weight && entry.keep.test(file) ? [{ family: entry.family, path: `${entry.directory}/files/${file}`, weight, style: /font-style:\s*italic/.test(block) ? 'italic' : 'normal', unicodeRange }] : []
    }))
  })
}

const banner = 'Generated by scripts/generate-font-table.mjs from the installed font packages. Do not edit: run the script.'

/** `font-display: block` shows the right font after a short blank instead of swapping in a fallback first. */
export function buildCss(list = faces()) {
  for (const face of list) if (!existsSync(join(root, face.path))) throw new Error(`missing font file: ${face.path}`)
  return `/* ${banner} */\n${list.map((face) => `@font-face{font-family:'${face.family}';font-style:${face.style};font-weight:${face.weight};font-display:block;src:url(../../../${face.path}) format('woff2');${face.unicodeRange ? `unicode-range:${face.unicodeRange};` : ''}}`).join('\n')}\n`
}

export function buildTable(list = faces()) {
  // Every weight of a family, and both Noto families, are cut into the same subsets, so each range is written once.
  const ranges = []
  const indexOf = (range) => { if (range === null) return null; let index = ranges.indexOf(range); if (index < 0) index = ranges.push(range) - 1; return index }
  const rows = list.map((face) => `  ${JSON.stringify([face.family, face.path.split('/').pop(), face.weight, face.style === 'italic' ? 1 : 0, indexOf(face.unicodeRange)])},`).join('\n')
  return `// ${banner}\n\n/** The unicode-range of each subset. */\nexport const fontRanges: readonly string[] = [\n${ranges.map((range) => `  ${JSON.stringify(range)},`).join('\n')}\n]\n\n/** Every bundled face in the order it is registered: family, WOFF2 file, weight, italic (1) or upright (0), and its entry in \`fontRanges\`. */\nexport const fontFaceRows: readonly (readonly [family: string, file: string, weight: string, italic: 0 | 1, range: number | null])[] = [\n${rows}\n]\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = faces()
  const fresh = { css: buildCss(list), table: buildTable(list) }
  let stale = 0
  for (const [kind, path] of Object.entries(outputs)) {
    if (process.argv.includes('--check')) {
      let committed = ''
      try { committed = readFileSync(path, 'utf8') } catch { /* Reported below as a difference. */ }
      if (committed !== fresh[kind]) { stale++; console.error(`${path} is out of date; run node scripts/generate-font-table.mjs`) }
    } else {
      writeFileSync(path, fresh[kind])
      console.log(`wrote ${path} (${fresh[kind].length} characters)`)
    }
  }
  if (stale) process.exit(1)
  if (process.argv.includes('--check')) console.log(`${list.length} bundled font faces are up to date`)
}
